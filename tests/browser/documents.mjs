import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

export async function checkDocuments({ page, reader, readerEmail, origin, output, post, browserRequest, record, restart }) {
  const originalPath = new URL(page.url()).pathname;
  const firstBytes = Buffer.from('%PDF-1.4\nDocument browser fixture: first version\n%%EOF');
  const secondBytes = Buffer.from('%PDF-1.4\nDocument browser fixture: second version\n%%EOF');
  await page.goto(origin);
  await page.locator('[data-dialog-open="new-evaluation"]').first().click();
  const creation = page.getByRole('dialog', { name: 'Neue Evaluation', exact: true });
  await creation.getByLabel('Name der Evaluation').fill('Dokumentenprüfung');
  await creation.getByRole('button', { name: 'Evaluation anlegen', exact: false }).click();
  await page.waitForURL(/\/evaluations\//);
  const casePath = new URL(page.url()).pathname;
  async function caseVersion() {
    await page.goto(`${origin}${casePath}`);
    return page.locator('#evaluation-workspace').getAttribute('data-version');
  }
  await page.goto(`${origin}${casePath}/candidates`);
  let version = await page.locator('#candidate-workspace').getAttribute('data-version');
  assert.equal((await post(page, `${casePath}/candidates`, { action: 'add-candidate', 'Input.Model': 'Dokumentenauto', version })).status(), 0);
  await page.goto(`${origin}${casePath}/offers/edit`);
  await page.locator('#offer-candidate').selectOption(await page.locator('#offer-candidate option').nth(1).getAttribute('value'));
  await page.locator('#offer-currency').fill('EUR');
  await page.locator('#offer-Name').fill('Dokumentenofferte');
  await page.getByRole('button', { name: /Offerte anlegen/ }).click();
  await page.locator('#offer-workspace').waitFor();
  const offerPath = new URL(page.url()).pathname;
  await page.getByRole('link', { name: 'Dokument hinzufügen', exact: true }).click();
  await page.getByLabel('Name des Dokuments').fill('Vertragsunterlagen');
  await page.getByLabel('Datei', { exact: true }).setInputFiles({ name: 'vertrag.pdf', mimeType: 'application/pdf', buffer: firstBytes });
  await page.getByLabel('Notiz zur Dateiversion', { exact: false }).fill('Erster Stand');
  await page.getByRole('button', { name: 'Datei hochladen', exact: true }).click();
  await page.locator('[data-document-id]').waitFor();
  assert.equal(new URL(page.url()).hash, '#documents');
  const documentId = await page.locator('[data-document-id]').getAttribute('data-document-id');
  const downloadPath = `${casePath}/documents/${documentId}/1`;
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Herunterladen', exact: true }).click();
  const received = await download;
  assert.equal(received.suggestedFilename(), 'vertrag.pdf');
  assert.deepEqual(await readFile(await received.path()), firstBytes);
  assert.ok(!(await page.content()).includes('File_ContentId'));
  record('Document upload and authenticated download preserve the original filename and exact bytes');

  await page.getByRole('link', { name: 'Neue Version erfassen', exact: true }).click();
  await page.locator('#offer-Name').fill('Dokumentenofferte ergänzt');
  await page.locator('#save-offer').click();
  await page.locator('#offer-workspace[data-revision="2"]').waitFor();
  await page.getByRole('link', { name: 'Neue Dateiversion', exact: true }).click();
  await page.getByLabel('Datei', { exact: true }).setInputFiles({ name: 'vertrag-neu.pdf', mimeType: 'application/pdf', buffer: secondBytes });
  await page.getByLabel('Notiz zur Dateiversion', { exact: false }).fill('Nachverhandelt');
  await page.getByRole('button', { name: 'Datei hochladen', exact: true }).click();
  await page.locator('[data-document-id]').waitFor();
  await page.locator('#documents summary').click();
  assert.equal(await page.locator('[data-document-version]').count(), 2);
  assert.match(await page.locator('[data-document-version="2"]').textContent(), /Version 2/);
  assert.equal(await (await browserRequest(page, downloadPath)).text(), firstBytes.toString());
  await page.locator('#documents').screenshot({ path: join(output, '18-document-history-desktop.png') });
  await page.goto(`${origin}${offerPath}?revision=1`);
  assert.equal(await page.locator('[data-document-version]').count(), 1);
  assert.equal(await page.getByRole('link', { name: 'Neue Dateiversion', exact: true }).count(), 0);
  assert.ok(!(await page.locator('#documents').textContent()).includes('vertrag-neu.pdf'));
  await restart();
  await page.goto(`${origin}${offerPath}`);
  assert.match(await page.locator('#documents').textContent(), /vertrag-neu.pdf/);
  assert.equal(await (await browserRequest(page, downloadPath)).text(), firstBytes.toString());
  record('File history retains earlier bytes and offer-version references across application restarts');

  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'share', email: readerEmail, access: 'Reader', version })).status(), 200);
  await reader.page.goto(`${origin}${offerPath}`);
  assert.equal(await reader.page.getByRole('link', { name: 'Dokument hinzufügen', exact: true }).count(), 0);
  assert.equal(await (await browserRequest(reader.page, downloadPath)).text(), firstBytes.toString());
  assert.equal((await browserRequest(reader.page, `${offerPath}/documents/upload`)).status(), 403);
  async function multipart(target, path, fields, includeToken = true) {
    const token = includeToken ? await target.locator('input[name="__RequestVerificationToken"]').first().inputValue() : null;
    return target.evaluate(async ({ path, fields, token }) => {
      const form = new FormData();
      for (const [key, value] of Object.entries(fields)) form.append(key, value);
      if (token) form.append('__RequestVerificationToken', token);
      form.append('upload', new Blob(['unauthorized'], { type: 'application/pdf' }), 'file.pdf');
      return (await fetch(path, { method: 'POST', body: form, redirect: 'manual' })).status;
    }, { path, fields, token });
  }
  assert.equal(await multipart(reader.page, `${offerPath}/documents/upload`, { Version: String(Number(version) + 1), Name: 'Denied' }), 403);
  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'share', email: readerEmail, access: 'Editor', version })).status(), 200);
  await page.goto(`${origin}${offerPath}/documents/upload`);
  const stale = await page.locator('[name=Version]').inputValue();
  await page.getByLabel('Name des Dokuments').fill('Entwurf bleibt erhalten');
  await page.getByLabel('Datei', { exact: true }).setInputFiles({ name: 'draft.pdf', mimeType: 'application/pdf', buffer: firstBytes });
  await reader.page.goto(`${origin}${offerPath}/documents/upload/${documentId}`);
  await reader.page.getByLabel('Datei', { exact: true }).setInputFiles({ name: 'vertrag-final.pdf', mimeType: 'application/pdf', buffer: secondBytes });
  await reader.page.getByRole('button', { name: 'Datei hochladen', exact: true }).click();
  await reader.page.locator('[data-document-id]').waitFor();
  const conflict = page.waitForResponse(r => r.request().method() === 'POST' && r.url() === page.url());
  await page.getByRole('button', { name: 'Datei hochladen', exact: true }).click();
  assert.equal((await conflict).status(), 409);
  assert.equal(await page.getByLabel('Name des Dokuments').inputValue(), 'Entwurf bleibt erhalten');
  assert.equal(await page.locator('[name=Version]').inputValue(), stale);
  assert.equal(await multipart(page, `${offerPath}/documents/upload`, { Version: stale, Name: 'No token' }, false), 400);
  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'revoke', userId: await page.locator('.share-row input[name=userId]').inputValue(), version })).status(), 200);
  assert.equal((await browserRequest(reader.page, downloadPath)).status(), 403);
  record('Document sharing covers direct upload/download requests, editors, revocation, CSRF and concurrent changes');

  await page.goto(`${origin}${offerPath}`);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#documents summary').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#documents').screenshot({ path: join(output, '19-documents-mobile.png') });
  await page.getByRole('link', { name: 'Neue Dateiversion', exact: true }).click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: join(output, '20-document-upload-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto(`${origin}${casePath}`);
  const exported = page.waitForEvent('download');
  await page.getByRole('link', { name: /Exportieren/ }).click();
  const zip = await exported;
  assert.match(zip.suggestedFilename(), /\.zip$/);
  const zipPath = join(output, 'document-export.zip'); await zip.saveAs(zipPath);
  await page.goto(origin);
  await page.locator('details').filter({ has: page.getByText('Evaluation importieren', { exact: true }) }).locator('summary').click();
  await page.getByLabel('Exportdatei (JSON oder ZIP)').setInputFiles(zipPath);
  await page.getByRole('button', { name: 'Als neue Evaluation importieren', exact: true }).click();
  await page.waitForURL(/\/evaluations\//);
  const importedPath = new URL(page.url()).pathname;
  assert.notEqual(importedPath, casePath); assert.equal(await page.locator('.share-row').count(), 0);
  await page.goto(`${origin}${importedPath}/offers`);
  await page.locator('.offer-card a').first().click();
  await page.locator('[data-document-id]').waitFor();
  const copiedId = await page.locator('[data-document-id]').getAttribute('data-document-id');
  assert.notEqual(copiedId, documentId);
  assert.equal(await page.locator('[data-document-version]').count(), 3);
  assert.equal(await (await browserRequest(page, `${importedPath}/documents/${copiedId}/1`)).text(), firstBytes.toString());
  await page.goto(`${origin}${offerPath}`);
  const deleted = page.waitForResponse(r => r.url().endsWith(offerPath) && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Dokument löschen', exact: true }).click();
  assert.equal((await deleted).status(), 200);
  await page.locator('#documents').getByText('Zu diesem Offertstand sind noch keine Dokumente abgelegt.').waitFor();
  assert.equal((await browserRequest(page, downloadPath)).status(), 404);
  assert.equal(await (await browserRequest(page, `${importedPath}/documents/${copiedId}/1`)).text(), firstBytes.toString());
  record('Responsive document screens and ZIP import retain all file versions independently of deleted originals');
  await page.goto(`${origin}${originalPath}`);
}
