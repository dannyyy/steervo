import assert from 'node:assert/strict';
import { join } from 'node:path';

export async function checkOffers({ page, reader, readerEmail, origin, output, post, browserRequest, record }) {
  const originalPath = new URL(page.url()).pathname;
  await page.goto(origin);
  await page.locator('[data-dialog-open="new-evaluation"]').first().click();
  const creation = page.getByRole('dialog', { name: 'Neue Evaluation', exact: true });
  await creation.getByLabel('Name der Evaluation').fill('Offertenprüfung');
  await creation.getByRole('button', { name: 'Evaluation anlegen', exact: false }).click();
  await page.waitForURL(/\/evaluations\//);
  const casePath = new URL(page.url()).pathname;
  async function caseVersion() {
    await page.goto(`${origin}${casePath}`);
    return page.locator('#evaluation-workspace').getAttribute('data-version');
  }
  async function change(operation) {
    const version = await page.locator('#offer-workspace').getAttribute('data-version');
    await operation();
    await page.waitForFunction(old => document.querySelector('#offer-workspace')?.dataset.version !== old, version);
    await page.waitForFunction(() => !document.querySelector('.htmx-settling, .htmx-request'));
  }
  await page.getByRole('link', { name: 'Offerten', exact: true }).click();
  await page.getByText('Erfasse zuerst ein Auto, damit du ihm Offerten zuordnen kannst.', { exact: false }).waitFor();
  await page.goto(`${origin}${casePath}/candidates`);
  let version = await page.locator('#candidate-workspace').getAttribute('data-version');
  assert.equal((await post(page, `${casePath}/candidates`, { action: 'add-candidate', 'Input.Model': 'Angebotsauto', version })).status(), 0);
  const initial = JSON.parse(await (await browserRequest(page, `${casePath}?handler=Export`)).text());
  const candidateId = initial.candidates[0].id;
  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'add-criterion', name: 'Kaufrecht', type: 'Boolean', priority: 'Required', scope: 'Offer', version })).status(), 200);
  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'add-criterion', name: 'Zins', type: 'Measurement', priority: 'Required', scope: 'Offer', threshold: '3', unit: '%', comparison: 'AtMost', version })).status(), 200);
  const definition = JSON.parse(await (await browserRequest(page, `${casePath}?handler=Export`)).text());
  const booleanId = definition.criteria.find(criterion => criterion.type === 'Boolean').id;
  const measurementId = definition.criteria.find(criterion => criterion.type === 'Measurement').id;
  await page.goto(`${origin}${casePath}/offers`);
  await page.getByRole('link', { name: /Offerte erfassen/ }).click();
  await page.getByRole('link', { name: /Alle Offerten/ }).click();
  assert.equal(new URL(page.url()).pathname, `${casePath}/offers`);
  await page.goto(`${origin}${casePath}/candidates/${candidateId}`);
  await page.getByRole('link', { name: 'Offerten für dieses Auto', exact: false }).click();
  await page.getByRole('link', { name: /Offerte erfassen/ }).click();
  assert.equal(await page.locator('#offer-candidate').inputValue(), candidateId);
  assert.equal(await page.locator('#offer-VehicleDescription').inputValue(), 'Angebotsauto');
  await page.locator('#offer-currency').fill('eur');
  await page.locator('#offer-Name').fill('Anbieter Nord');
  await page.getByRole('button', { name: /Offerte anlegen/ }).click();
  await page.locator('#offer-workspace').waitFor();
  const firstPath = new URL(page.url()).pathname;
  const firstId = firstPath.split('/').at(-1);
  assert.equal(await page.locator('#offer-workspace').getAttribute('data-revision'), '1');
  assert.match(await page.locator('.offer-missing').textContent(), /Basispreis/);
  record('Offers can start incomplete, inherit their candidate and establish the evaluation currency');

  await page.getByRole('link', { name: 'Neue Version erfassen', exact: true }).click();
  assert.equal(await page.locator('#offer-currency').inputValue(), 'EUR');
  assert.equal(await page.locator('#offer-currency').getAttribute('readonly'), 'readonly');
  await page.locator('#offer-Provider').fill('Anbieter Nord');
  await page.locator('#offer-Lender').fill('Finanzierungspartner');
  await page.locator('#offer-kind').selectOption('Leasing');
  await page.locator('#offer-commitment').selectOption('NonBinding');
  for (const [name, value] of Object.entries({ BasePrice: '27800', TermMonths: '24', AnnualInterestPercent: '2.75', MonthlyPayment: '640', DownPayment: '0', ResidualPayment: '14500', IncludedKilometresPerYear: '12000', ExcessKilometrePrice: '0.18', UnusedKilometreCredit: '0', IssuedOn: '2026-10-01', ValidUntil: '2026-09-01', DeliveryNotes: 'Nach Absprache' }))
    await page.locator(`#offer-${name}`).fill(value);
  async function addLine(name, kind, price, amount) {
    await page.getByRole('button', { name: /Position hinzufügen/ }).click();
    const line = page.locator('[data-offer-line]').last();
    await line.getByLabel('Bezeichnung der Position', { exact: true }).fill(name);
    await line.getByLabel('Art', { exact: true }).selectOption(kind);
    await line.getByLabel('Preisangabe', { exact: true }).selectOption(price);
    if (amount !== undefined) await line.getByLabel('Betrag', { exact: false }).fill(amount);
    return line;
  }
  await addLine('Übergabe', 'Fee', 'Amount', '275');
  const benefit = await addLine('Servicepaket', 'Benefit', 'Included');
  await benefit.getByLabel('Wirkung', { exact: true }).selectOption('CostSaving');
  await benefit.getByLabel('Kostenbereich').selectOption('Service');
  await benefit.getByLabel('Dauer in Monaten').fill('24');
  await addLine('Zubehör', 'Accessory', 'Unknown');
  const temporary = await addLine('Entfernen', 'Equipment', 'Included');
  await temporary.getByRole('button', { name: 'Position entfernen', exact: true }).click();
  await page.locator('[data-offer-line]').last().getByRole('button', { name: 'Position nach oben' }).click();
  await page.locator('#offer-change-note').fill('Angaben vom Anbieter ergänzt.');
  const invalid = page.waitForResponse(response => response.request().method() === 'POST' && response.url() === page.url());
  await page.locator('#save-offer').click();
  assert.equal((await invalid).status(), 422);
  assert.equal(await page.locator('#offer-AnnualInterestPercent').inputValue(), '2.75');
  assert.equal(await page.locator('[data-offer-line]').count(), 3);
  assert.equal(await page.locator('[data-offer-line]').nth(1).getByLabel('Bezeichnung der Position', { exact: true }).inputValue(), 'Zubehör');
  await page.locator('#offer-ValidUntil').fill('2026-11-01');
  await page.locator('#save-offer').click();
  await page.locator('#offer-workspace[data-revision="2"]').waitFor();
  assert.match(await page.locator('.offer-value-groups [data-offer-field="DownPayment"]').textContent(), /0,00\s+EUR/);
  assert.match(await page.locator('.offer-positions [data-offer-line-kind="Benefit"]').textContent(), /Inklusive/);
  assert.match(await page.locator('.offer-positions [data-offer-line-kind="Accessory"]').textContent(), /Preis offen/);
  const boolean = page.locator(`[data-offer-assessment="${booleanId}"]`);
  const measurement = page.locator(`[data-offer-assessment="${measurementId}"]`);
  await boolean.getByLabel('Deine Angabe').selectOption('true');
  await change(() => boolean.getByRole('button', { name: 'Einschätzung speichern', exact: true }).click());
  await measurement.getByLabel('Deine Angabe').fill('2.75');
  await change(() => measurement.getByRole('button', { name: 'Einschätzung speichern', exact: true }).click());
  assert.equal(await measurement.getAttribute('data-result'), 'Met');
  record('Structured offer fields, line ordering and validation retain drafts; zero, inclusive and open prices remain distinct');

  await page.getByRole('link', { name: 'Neue Version erfassen', exact: true }).click();
  await page.locator('#offer-MonthlyPayment').fill('610');
  await page.locator('#offer-commitment').selectOption('Binding');
  await page.locator('[data-offer-line]').first().getByLabel('Preisangabe').selectOption('Included');
  await page.locator('#offer-change-note').fill('Rate und Übergabe nachverhandelt.');
  await page.locator('#save-offer').click();
  await page.locator('#offer-workspace[data-revision="3"]').waitFor();
  assert.equal(await boolean.getAttribute('data-stale'), 'true');
  assert.equal(await boolean.getAttribute('data-result'), 'Unknown');
  assert.equal(await boolean.getByLabel('Deine Angabe').inputValue(), 'true');
  assert.match(await page.locator('[data-offer-change="MonthlyPayment"]').textContent(), /640,00.*610,00/s);
  await change(() => boolean.getByRole('button', { name: 'Für aktuelle Version bestätigen' }).click());
  assert.equal(await boolean.getAttribute('data-result'), 'Met');
  assert.equal(await measurement.getAttribute('data-stale'), 'true');
  await page.locator('.offer-history').getByRole('link', { name: 'Version 2', exact: true }).click();
  await page.locator('#offer-workspace[data-revision="2"]').waitFor();
  assert.match(await page.locator('.offer-value-groups [data-offer-field="MonthlyPayment"]').textContent(), /640,00\s+EUR/);
  assert.equal(await page.locator('[data-offer-assessment]').count(), 0);
  assert.equal(await page.getByRole('link', { name: 'Neue Version erfassen', exact: true }).count(), 0);
  await page.goto(`${origin}${firstPath}`);
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: join(output, '15-offer-history-desktop.png'), fullPage: true });
  record('Negotiation appends immutable versions and differences; assessments require confirmation for a new version');

  await page.goto(`${origin}${casePath}/offers/edit?candidateId=${candidateId}`);
  assert.equal(await page.locator('#offer-currency').inputValue(), 'EUR');
  const badCurrency = await post(page, `${casePath}/offers/edit`, { Version: await page.locator('[name=Version]').inputValue(), 'Input.CandidateId': candidateId, 'Input.Name': 'Blocked currency', 'Input.Currency': 'USD' });
  assert.equal(badCurrency.status(), 422);
  await page.locator('#offer-Name').fill('Anbieter Süd');
  await page.locator('#offer-Provider').fill('Anbieter Süd');
  await page.locator('#offer-kind').selectOption('Leasing');
  await page.locator('#offer-MonthlyPayment').fill('625');
  await page.locator('#save-offer').click();
  await page.locator('#offer-workspace').waitFor();
  const secondId = new URL(page.url()).pathname.split('/').at(-1);
  await page.goto(`${origin}${casePath}/offers/compare?first=${firstId}&second=${secondId}`);
  const monthly = page.locator('[data-offer-comparison-field="MonthlyPayment"]');
  assert.equal((await monthly.locator(`[data-offer-cell="${firstId}"]`).textContent()).trim(), '610,00');
  assert.equal((await monthly.locator(`[data-offer-cell="${secondId}"]`).textContent()).trim(), '625,00');
  await page.screenshot({ path: join(output, '16-offer-comparison-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: join(output, '17-offer-comparison-mobile.png'), fullPage: true });
  await page.goto(`${origin}${casePath}/offers/edit/${secondId}`);
  await page.locator('#offer-Notes').fill('Mobile Ergänzung.');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#save-offer').click();
  await page.locator('#offer-workspace[data-revision="2"]').waitFor();
  await change(() => page.getByRole('button', { name: 'Offerte archivieren', exact: true }).click());
  await page.goto(`${origin}${casePath}/offers`);
  assert.equal(await page.locator('.offer-card').count(), 1);
  await page.getByLabel('Archivierte Offerten anzeigen').check();
  await page.getByRole('button', { name: 'Vergleich anzeigen' }).click();
  assert.equal(await page.locator('.offer-card').count(), 2);
  await page.goto(`${origin}${casePath}/offers/edit/${secondId}`);
  assert.equal(new URL(page.url()).pathname, `${casePath}/offers/${secondId}`);
  await page.getByRole('button', { name: 'Offerte wieder aktivieren', exact: true }).waitFor();
  await page.setViewportSize({ width: 1440, height: 1050 });
  record('Dealer comparison and mobile editing work; currency cannot change and archived offers remain accessible');

  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'share', email: readerEmail, access: 'Reader', version })).status(), 200);
  await reader.page.goto(`${origin}${firstPath}`);
  assert.equal(await reader.page.locator('[data-offer-version]').count(), 3);
  assert.equal(await reader.page.locator('.assessment-form').count(), 0);
  assert.equal((await browserRequest(reader.page, `${casePath}/offers/edit/${firstId}`)).status(), 403);
  await reader.page.goto(`${origin}${firstPath}`);
  version = await reader.page.locator('#offer-workspace').getAttribute('data-version');
  for (const action of ['archive-offer', 'restore-offer', 'assess-offer', 'clear-assessment'])
    assert.equal((await post(reader.page, firstPath, { action, version, criterionId: booleanId, booleanValue: 'false' })).status(), 403);
  assert.equal((await post(reader.page, `${casePath}/offers/edit/${firstId}`, { Version: version, 'Input.Name': 'Forbidden edit' })).status(), 403);
  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'share', email: readerEmail, access: 'Editor', version })).status(), 200);
  await reader.page.goto(`${origin}${firstPath}`);
  const readerBoolean = reader.page.locator(`[data-offer-assessment="${booleanId}"]`);
  await readerBoolean.getByLabel('Deine Angabe').selectOption('false');
  const assessed = reader.page.waitForResponse(response => response.url().endsWith(firstPath) && response.request().method() === 'POST');
  await readerBoolean.getByRole('button', { name: 'Einschätzung speichern' }).click();
  assert.equal((await assessed).status(), 200);
  await reader.page.waitForFunction(() => !document.querySelector('.htmx-settling, .htmx-request'));
  await page.goto(`${origin}${casePath}/offers/edit/${firstId}`);
  const staleVersion = await page.locator('[name=Version]').inputValue();
  assert.equal((await post(reader.page, firstPath, { action: 'assess-offer', version: staleVersion, criterionId: measurementId, measurementValue: '2.75' })).status(), 200);
  await page.locator('#offer-MonthlyPayment').fill('599');
  const conflict = page.waitForResponse(response => response.url() === page.url() && response.request().method() === 'POST');
  await page.locator('#save-offer').click();
  assert.equal((await conflict).status(), 409);
  assert.equal(await page.locator('#offer-MonthlyPayment').inputValue(), '599');
  assert.equal(await page.locator('[name=Version]').inputValue(), staleVersion);
  assert.equal((await browserRequest(page, `${casePath}/offers/edit/${firstId}`, { Version: staleVersion, 'Input.Name': 'No token' })).status(), 400);
  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'revoke', userId: await page.locator('.share-row form input[name=userId]').inputValue(), version })).status(), 200);
  assert.equal((await browserRequest(reader.page, `${firstPath}?revision=1`)).status(), 403);
  const exported = JSON.parse(await (await browserRequest(page, `${casePath}?handler=Export`)).text());
  assert.equal(exported.version, 6);
  assert.equal(exported.currency, 'EUR');
  assert.equal(exported.offers.length, 2);
  assert.equal(exported.offers.find(offer => offer.id === firstId).revisions.length, 3);
  assert.equal(exported.offers.find(offer => offer.id === secondId).archived, true);
  record('Offer access checks cover history and direct writes; concurrency preserves drafts and revocation is immediate');

  await page.goto(origin);
  await page.locator('details').filter({ has: page.getByText('Evaluation importieren', { exact: true }) }).locator('summary').click();
  await page.getByLabel('Exportdatei (JSON oder ZIP)').setInputFiles({ name: 'offers.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported)) });
  await page.getByRole('button', { name: 'Als neue Evaluation importieren', exact: true }).click();
  await page.waitForURL(/\/evaluations\//);
  const imported = JSON.parse(await (await browserRequest(page, `${new URL(page.url()).pathname}?handler=Export`)).text());
  assert.equal(imported.currency, 'EUR');
  assert.equal(imported.offers.length, 2);
  assert.ok(imported.offers.every(offer => !exported.offers.some(original => original.id === offer.id)));
  assert.equal(imported.offers.find(offer => offer.revisions[0].terms.name === 'Anbieter Nord').revisions.length, 3);
  assert.equal(imported.offerAssessments.length, 2);
  assert.equal(await page.locator('.share-row').count(), 0);
  record('JSON import keeps offer histories, positions, currency and assessments with independent IDs and private access');
  await page.goto(`${origin}${originalPath}`);
  return { casePath, firstId };
}
