import { checkCostWorkflows } from './financial-workflows.mjs';
import assert from 'node:assert/strict';
import { join } from 'node:path';

export async function checkCosts({ page, reader, readerEmail, origin, output, post, browserRequest, record, restart }) {
  const originalPath = new URL(page.url()).pathname;
  async function save(operation, target = page) { await Promise.all([target.waitForNavigation({ waitUntil: 'load' }), operation()]); }
  await page.goto(origin);
  await page.locator('[data-dialog-open="new-evaluation"]').first().click();
  const creation = page.getByRole('dialog', { name: 'Neue Evaluation', exact: true });
  await creation.getByLabel('Name der Evaluation').fill('Kostenprüfung');
  await creation.getByRole('button', { name: 'Evaluation anlegen', exact: false }).click();
  await page.waitForURL(/\/evaluations\//);
  const casePath = new URL(page.url()).pathname;
  const costPath = `${casePath}/costs`;
  async function caseVersion() { await page.goto(`${origin}${casePath}`); return page.locator('#evaluation-workspace').getAttribute('data-version'); }
  async function exportCase() { return JSON.parse(await (await browserRequest(page, `${casePath}?handler=Export`)).text()); }
  await page.getByRole('link', { name: 'Kosten', exact: true }).click();
  await page.getByLabel('Beginn der Planung', { exact: true }).fill('2027-10');
  await page.getByLabel('Dauer in Monaten', { exact: true }).fill('15');
  await save(() => page.getByRole('button', { name: 'Zeitraum speichern', exact: true }).click());
  await page.locator('#cost-workspace').waitFor();
  await page.getByText('Die gemeinsame Währung wird bei der ersten Offerte festgelegt.', { exact: false }).waitFor();
  assert.equal(await page.getByRole('link', { name: /Kostenposition hinzufügen/ }).count(), 0);
  await page.goto(`${origin}${casePath}/candidates`);
  let version = await page.locator('#candidate-workspace').getAttribute('data-version');
  assert.equal((await post(page, `${casePath}/candidates`, { action: 'add-candidate', 'Input.Model': 'Planungsauto', version })).status(), 0);
  const candidateId = (await exportCase()).candidates[0].id;
  await page.goto(`${origin}${casePath}/offers/edit?candidateId=${candidateId}`);
  await page.locator('#offer-currency').fill('EUR'); await page.locator('#offer-Name').fill('Kostenbasis');
  await page.getByRole('button', { name: /Offerte anlegen/ }).click(); await page.locator('#offer-workspace').waitFor();
  async function addCost({ name, frequency = 'Monthly', amount, start = '1', end, candidate, direction = 'Expense' }) {
    await page.goto(`${origin}${costPath}`);
    await page.getByRole('link', { name: /Kostenposition hinzufügen/ }).click();
    await page.getByLabel('Bezeichnung der Kostenposition').fill(name);
    await page.getByLabel('Gilt für', { exact: true }).selectOption(candidate || '');
    await page.getByLabel('Zahlungsrhythmus', { exact: true }).selectOption(frequency);
    if (frequency !== 'Included') {
      await page.getByLabel('Art der Zahlung', { exact: true }).selectOption(direction);
      if (amount !== undefined) await page.getByLabel('Betrag je Zahlung', { exact: false }).fill(amount);
    }
    else { assert.equal(await page.locator('#Input_Amount').isDisabled(), true); assert.equal(await page.locator('#Input_Direction').isDisabled(), true); }
    await page.getByLabel('Erster Monat', { exact: true }).fill(start);
    if (end) await page.getByLabel('Letzter Monat', { exact: false }).fill(end);
    await save(() => page.getByRole('button', { name: 'Speichern', exact: true }).click());
    await page.locator('#cost-workspace').waitFor();
    return page.locator('[data-cost-id]').filter({ has: page.getByRole('heading', { name, exact: true }) }).getAttribute('data-cost-id');
  }
  const sharedMonthly = await addCost({ name: 'Parkplatz', amount: '25' });
  await addCost({ name: 'Jahresbetrag', frequency: 'Yearly', amount: '120', start: '2' });
  await addCost({ name: 'Einmalbetrag', frequency: 'Once', amount: '400', start: '3', candidate: candidateId });
  await addCost({ name: 'Befristeter Betrag', amount: '10', start: '4', end: '6', candidate: candidateId });
  await addCost({ name: 'Gutschrift', frequency: 'Once', amount: '50', start: '5', direction: 'Income', candidate: candidateId });
  await addCost({ name: 'Offener Betrag', start: '13', end: '15', candidate: candidateId });
  await addCost({ name: 'Service inklusive', frequency: 'Included', end: '12', candidate: candidateId });
  await addCost({ name: 'Bekannte Null', amount: '0', candidate: candidateId });
  assert.equal(await page.locator('[data-cost-net]').getAttribute('data-cost-net'), '995');
  assert.equal(await page.locator('[data-cost-missing]').getAttribute('data-cost-missing'), '1');
  assert.equal(await page.locator('[data-cost-id]').count(), 8);
  assert.match(await page.locator('[data-cost-period="2"]').textContent(), /145,00/);
  assert.match(await page.locator('[data-cost-period="5"]').textContent(), /-15,00/);
  const exported = await exportCase();
  assert.equal(exported.version, 7); assert.deepEqual(exported.costPlanning, { start: '2027-10-01', months: 15 });
  assert.equal(exported.costs.find(c => c.input.name === 'Bekannte Null').input.amount, 0);
  assert.equal(exported.costs.find(c => c.input.name === 'Offener Betrag').input.amount, null);
  assert.equal(exported.costs.find(c => c.input.name === 'Service inklusive').input.frequency, 'Included');
  await page.getByRole('link', { name: 'Jahre', exact: true }).click();
  assert.equal(await page.locator('[data-cost-period]').count(), 2);
  assert.match(await page.locator('[data-cost-period="1"]').textContent(), /595,00/);
  assert.match(await page.locator('[data-cost-period="4"]').textContent(), /400,00/);
  await page.screenshot({ path: join(output, '21-cost-planning-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: /Für alle Autos Diese Positionen/ }).click();
  assert.equal(await page.locator('[data-cost-net]').getAttribute('data-cost-net'), '615');
  assert.equal(await page.locator('[data-cost-id]').count(), 2);
  record('Cost planning reconciles one-off, monthly and annual payments, income, inclusive items, unknowns and calendar-year totals');

  await page.goto(`${origin}${costPath}?candidateId=${candidateId}`);
  await page.locator('#open-cost-plan').click();
  await page.getByLabel('Dauer in Monaten', { exact: true }).fill('12');
  await save(() => page.getByRole('button', { name: 'Zeitraum speichern', exact: true }).click());
  await page.locator('#cost-workspace').waitFor();
  assert.equal(await page.locator('[data-cost-missing]').count(), 0);
  await page.getByText('Ausserhalb des gewählten Zeitraums', { exact: true }).waitFor();
  await page.locator('#open-cost-plan').click();
  await page.getByLabel('Dauer in Monaten', { exact: true }).fill('15');
  await save(() => page.getByRole('button', { name: 'Zeitraum speichern', exact: true }).click()); await page.locator('#cost-workspace').waitFor();
  assert.equal(await page.locator('[data-cost-id]').count(), 8);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(await page.locator('.cost-row').evaluateAll(rows => rows.every(row => {
    const amount = row.querySelector('.cost-row-amount').getBoundingClientRect();
    const actions = row.querySelector('.cost-row-actions').getBoundingClientRect();
    return amount.bottom <= actions.top;
  })), 'Mobile cost actions must not overlap the amount or payment details');
  await page.screenshot({ path: join(output, '22-cost-planning-mobile.png'), fullPage: true });
  await page.locator(`[data-cost-id="${sharedMonthly}"]`).getByRole('link', { name: 'Bearbeiten', exact: true }).click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: join(output, '23-cost-edit-mobile.png'), fullPage: true });
  await page.getByLabel('Betrag je Zahlung', { exact: false }).fill('25.001');
  await page.locator('[data-cost-form]').evaluate(form => { form.noValidate = true; });
  const invalid = page.waitForResponse(r => r.request().method() === 'POST' && r.url() === page.url());
  await page.locator('#save-cost').click(); assert.equal((await invalid).status(), 422);
  assert.equal(await page.getByLabel('Betrag je Zahlung', { exact: false }).inputValue(), '25.001');
  await page.setViewportSize({ width: 1440, height: 1050 });
  await restart();
  await page.goto(`${origin}${costPath}?candidateId=${candidateId}`);
  assert.equal(await page.locator('[data-cost-net]').getAttribute('data-cost-net'), '995');
  record('Plan changes retain out-of-period items; validation preserves drafts; cost planning and editing work at 390px and after restart');

  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'share', email: readerEmail, access: 'Reader', version })).status(), 200);
  await reader.page.goto(`${origin}${costPath}?candidateId=${candidateId}`);
  assert.equal(await reader.page.getByRole('link', { name: /Kostenposition hinzufügen/ }).count(), 0);
  assert.equal((await browserRequest(reader.page, `${costPath}/edit/${sharedMonthly}`)).status(), 403);
  const current = await reader.page.locator('#cost-workspace').getAttribute('data-version');
  assert.equal((await post(reader.page, costPath, { action: 'remove-cost', Version: current, costId: sharedMonthly })).status(), 403);
  assert.equal((await post(reader.page, `${costPath}/edit`, { Version: current, 'Input.Name': 'Denied' })).status(), 403);
  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'share', email: readerEmail, access: 'Editor', version })).status(), 200);
  await page.goto(`${origin}${costPath}/edit/${sharedMonthly}`);
  const stale = await page.locator('[name=Version]').inputValue();
  await page.getByLabel('Betrag je Zahlung', { exact: false }).fill('111');
  await reader.page.goto(`${origin}${costPath}/edit/${sharedMonthly}`);
  await reader.page.getByLabel('Notiz / Grundlage', { exact: false }).fill('Reviewed by editor');
  await save(() => reader.page.locator('#save-cost').click(), reader.page); await reader.page.locator('#cost-workspace').waitFor();
  const conflict = page.waitForResponse(r => r.request().method() === 'POST' && r.url() === page.url());
  await page.locator('#save-cost').click(); assert.equal((await conflict).status(), 409);
  assert.equal(await page.getByLabel('Betrag je Zahlung', { exact: false }).inputValue(), '111');
  assert.equal(await page.locator('[name=Version]').inputValue(), stale);
  assert.equal((await browserRequest(page, `${costPath}/edit/${sharedMonthly}`, { Version: stale, 'Input.Name': 'No token' })).status(), 400);
  version = await caseVersion();
  assert.equal((await post(page, casePath, { action: 'revoke', userId: await page.locator('.share-row input[name=userId]').inputValue(), version })).status(), 200);
  assert.equal((await browserRequest(reader.page, costPath)).status(), 403);
  record('Cost reads and writes enforce roles, revoked access, antiforgery and concurrent-edit protection');

  await page.goto(`${origin}${casePath}/candidates`); version = await page.locator('#candidate-workspace').getAttribute('data-version');
  assert.equal((await post(page, `${casePath}/candidates`, { action: 'copy-candidate', itemId: candidateId, copyName: 'Kostenkopie', version })).status(), 0);
  const withCopy = await exportCase(); const copyId = withCopy.candidates.find(c => c.model === 'Kostenkopie').id;
  assert.equal(withCopy.costs.filter(c => c.input.candidateId === copyId).length, 6); assert.equal(withCopy.costs.length, 14);
  await page.goto(origin);
  await page.getByRole('button', { name: 'Evaluation importieren', exact: true }).click();
  await page.getByLabel('Exportdatei (JSON oder ZIP)').setInputFiles({ name: 'costs.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(withCopy)) });
  await page.getByRole('button', { name: 'Als neue Evaluation importieren', exact: true }).click(); await page.waitForURL(/\/evaluations\//);
  const importedPath = new URL(page.url()).pathname;
  const imported = JSON.parse(await (await browserRequest(page, `${importedPath}?handler=Export`)).text());
  assert.deepEqual(imported.costPlanning, withCopy.costPlanning); assert.equal(imported.costs.length, 14);
  assert.ok(imported.costs.every(c => !withCopy.costs.some(o => o.id === c.id)));
  assert.ok(imported.costs.filter(c => c.input.candidateId).every(c => imported.candidates.some(car => car.id === c.input.candidateId)));
  await page.goto(`${origin}${casePath}/candidates`); version = await page.locator('#candidate-workspace').getAttribute('data-version');
  assert.equal((await post(page, `${casePath}/candidates`, { action: 'remove-candidate', itemId: candidateId, version })).status(), 200);
  const remaining = await exportCase(); assert.equal(remaining.costs.length, 8); assert.equal(remaining.costs.filter(c => !c.input.candidateId).length, 2);
  await page.goto(`${origin}${costPath}?candidateId=${copyId}`);
  assert.equal(await page.locator('[data-cost-net]').getAttribute('data-cost-net'), '995');
  const zeroCopyId = remaining.costs.find(c => c.input.name === 'Bekannte Null').id;
  await page.locator(`[data-cost-id="${zeroCopyId}"]`).getByRole('button', { name: 'Kostenposition löschen', exact: true }).click();
  await save(() => page.locator('[data-confirm-accept]').click());
  await page.waitForURL(url => url.pathname === costPath && url.hash === '#cost-items');
  assert.equal(await page.locator('[data-cost-id]').count(), 7);
  assert.equal(await page.locator('[data-cost-net]').getAttribute('data-cost-net'), '995');
  assert.equal((await exportCase()).costs.some(c => c.id === zeroCopyId), false);
  record('Candidate copies and JSON import retain independent costs, timing and scope; candidate and cost deletion preserve unrelated entries');
  await restart();
  await checkCostWorkflows({ page, reader, readerEmail, origin, casePath, candidateId: copyId, costId: sharedMonthly, post, record });
  await page.goto(`${origin}${originalPath}`);
}
